// Renders docs-src/**/*.md into src/pages/docs/ (pure: reads files, writes nothing).
// Imported by scripts/gen-docs.ts under Node, so it uses .ts extensions and only render.ts.
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { docRefs } from "../data/versions.ts";
import { buildCtx, renderTemplate } from "./render.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const walk = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );

const FRONTMATTER = /^---\n[\s\S]*?\n---\n/;

/** Repo-relative (to apps/site) output path -> rendered content, before formatting. */
export function generate(): Map<string, string> {
  const adopt = JSON.parse(readFileSync(join(root, "src/data/hull/adopt.json"), "utf8")) as {
    assess: { url: string; sha256: string };
  };
  const ctx = buildCtx(undefined, {
    ...docRefs,
    assessUrl: adopt.assess.url,
    assessSha: adopt.assess.sha256,
  });
  const out = new Map<string, string>();
  const srcDir = join(root, "docs-src");
  for (const abs of walk(srcDir).filter((f) => f.endsWith(".md"))) {
    const rel = relative(srcDir, abs);
    const rendered = renderTemplate(readFileSync(abs, "utf8"), ctx, rel);
    const header = `<!-- generated by scripts/gen-docs.ts from docs-src/${rel}; edit that -->\n`;
    const fm = rendered.match(FRONTMATTER)?.[0] ?? "";
    out.set(`src/pages/docs/${rel}`, fm + header + rendered.slice(fm.length));
  }
  return out;
}

/** Paths whose committed copy (`read` returns undefined when missing) differs from the map. */
export function diffGenerated(
  map: Map<string, string>,
  read: (path: string) => string | undefined,
): string[] {
  return [...map].filter(([path, content]) => read(path) !== content).map(([path]) => path);
}
