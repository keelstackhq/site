import { execFileSync } from "node:child_process";
import { expect, test } from "vite-plus/test";
import { diffGenerated, driftMessage } from "../lib/generate.ts";

test("committed generated docs match docs-src and versions.ts", () => {
  expect(() =>
    execFileSync("node", ["scripts/gen-docs.ts", "--check"], { stdio: "pipe", encoding: "utf8" }),
  ).not.toThrow();
});

const read = (p: string) => (p === "a.md" ? "one" : "changed");

test("diffGenerated returns the paths whose committed copy differs", () => {
  const map = new Map([
    ["a.md", "one"],
    ["b.md", "two"],
  ]);
  expect(diffGenerated(map, read)).toEqual(["b.md"]);
  expect(diffGenerated(map, () => undefined)).toEqual(["a.md", "b.md"]);
});

const readOrphan = (p: string) =>
  p === "src/pages/docs/old.md" ? "<!-- generated by scripts/gen-docs.ts from x -->" : "hand";

test("an orphan generated page is reported, a hand-written page is not", () => {
  const existing = ["src/pages/docs/old.md", "src/pages/docs/hand.md"];
  expect(diffGenerated(new Map(), readOrphan, existing)).toEqual(["src/pages/docs/old.md"]);
});

test("the drift message names each file and the gen command", () => {
  const m = driftMessage(["src/pages/docs/a.md", "src/pages/docs/b.md"]);
  expect(m).toContain("src/pages/docs/a.md");
  expect(m).toContain("src/pages/docs/b.md");
  expect(m).toContain("pnpm --filter @keelstackhq/site gen");
});
